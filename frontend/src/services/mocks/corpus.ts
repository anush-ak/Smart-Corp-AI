function pipeline(status: KnowledgeDocument['status']): ProcessingStep[] {
  const order: ProcessingStep['key'][] = ['uploaded', 'extracted', 'chunked', 'embedded', 'indexed']
  const labels: Record<ProcessingStep['key'], string> = {
    uploaded: 'Uploaded',
    extracted: 'Extracted',
    chunked: 'Chunked',
    embedded: 'Embedded',
    indexed: 'Indexed',
  }
  const details: Record<ProcessingStep['key'], string> = {
    uploaded: 'Validated and stored in object storage',
    extracted: 'Text extracted from source pages',
    chunked: 'Split into overlapping passages',
    embedded: 'Vectors generated for pgvector',
    indexed: 'Available to permission-aware retrieval',
  }
  const stageIndex =
    status === 'uploading' ? 0 : status === 'processing' ? 1 : status === 'indexing' ? 3 : status === 'ready' ? 5 : 2

  return order.map((key, index) => {
    const stepStatus: ProcessingStep['status'] =
      status === 'failed' && index >= stageIndex
        ? index === stageIndex
          ? 'failed'
          : 'pending'
        : index < stageIndex
          ? 'complete'
          : index === stageIndex
            ? 'active'
            : 'pending'
    return {
      key,
      label: labels[key],
      status: stepStatus,
      detail: details[key],
      at: index < stageIndex ? '2026-09-12T10:20:00Z' : undefined,
    }
  })
}

